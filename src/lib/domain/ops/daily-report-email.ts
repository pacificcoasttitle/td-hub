function renderSectionHtml<T>(title: string, result: SectionResult<T>, renderData: (data: T) => string): string {
  const body = result.ok
    ? renderData(result.data)
    : `<p style="margin:0;color:${RED};font-weight:700;">⚠️ This section could not load: ${escapeHtml(result.error)}</p>`;

  return `
    <section style="padding-top:22px;">
      <h2 style="margin:0 0 12px;color:${NAVY};font-size:16px;">${escapeHtml(title)}</h2>
      ${body}
    </section>`;
}

function renderAttentionHtml(items: string[]): string {
  return `
    <section style="padding-top:22px;">
      <h2 style="margin:0 0 12px;color:${NAVY};font-size:16px;">ATTENTION REQUIRED</h2>
      <ul style="margin:0;padding-left:20px;color:#111827;">
        ${items.map((item) => `<li style="margin-bottom:6px;">${escapeHtml(item)}</li>`).join('')}
      </ul>
    </section>`;
}

function metricGrid(items: Array<[string, string | number]>): string {
  return `<table cellspacing="0" cellpadding="0" style="width:100%;border-collapse:collapse;border:1px solid ${BORDER};">
    ${items.map(([label, value]) => `
      <tr>
        <td style="padding:8px 10px;border-bottom:1px solid ${BORDER};color:${MUTED};font-size:13px;">${escapeHtml(label)}</td>
        <td style="padding:8px 10px;border-bottom:1px solid ${BORDER};text-align:right;font-weight:700;">${escapeHtml(String(value))}</td>
      </tr>`).join('')}
  </table>`;
}

function renderSyncRows(rows: SyncHealthRow[]): string {
  if (rows.length === 0) return emptyState('No cron runs found in this window.');
  return table(['Job', 'Runs', 'Succeeded', 'Failed', 'Avg duration', 'Last run'], rows.map((row) => [
    row.jobType,
    String(row.runs),
    String(row.succeeded),
    String(row.failed),
    `${row.avgDurationSeconds.toFixed(1)}s`,
    formatPacific(row.lastRun),
  ]));
}

function renderVendorRows(rows: VendorApiHealthRow[]): string {
  return table(['Vendor', 'Calls', 'Success', 'Errors', 'Success Rate', 'Last Failure'], rows.map((row) => [
    row.vendor,
    String(row.calls),
    String(row.success),
    String(row.errors),
    `${row.successRate.toFixed(1)}%`,
    formatPacific(row.lastFailure),
  ]));
}

function renderCountRows(title: string, rows: CplVendorCount[]): string {
  if (rows.length === 0) return `<p style="margin:8px 0;color:${MUTED};font-size:13px;">${escapeHtml(title)}: 0</p>`;
  return `<p style="margin:12px 0 6px;color:${MUTED};font-size:13px;">${escapeHtml(title)}</p>${table(['Name', 'Count'], rows.map((row) => [row.vendor, String(row.count)]))}`;
}

function renderGrowthRows(items: GrowthItem[]): string {
  return table(['Metric', 'Total', 'Delta'], items.map((item) => [item.label, String(item.total), formatDelta(item.delta)]));
}

function renderFailureRows(rows: FailureDetailRow[]): string {
  if (rows.length === 0) return emptyState('No failures found.');
  return table(['Timestamp', 'Category', 'Vendor / Job', 'Order', 'Error', 'Remediation'], rows.map((row) => [
    formatPacific(row.timestamp),
    row.category,
    row.vendorOrJob,
    row.orderReference ?? '—',
    row.errorMessage,
    row.remediationStatus,
  ]));
}

function table(headers: string[], rows: string[][]): string {
  return `<table cellspacing="0" cellpadding="0" style="width:100%;border-collapse:collapse;border:1px solid ${BORDER};font-size:12px;">
    <thead><tr style="background:#F9FAFB;">${headers.map((header) => `<th style="padding:8px;border-bottom:1px solid ${BORDER};text-align:left;color:${MUTED};">${escapeHtml(header)}</th>`).join('')}</tr></thead>
    <tbody>${rows.map((row) => `<tr>${row.map((cell) => `<td style="padding:8px;border-bottom:1px solid ${BORDER};vertical-align:top;">${escapeHtml(cell)}</td>`).join('')}</tr>`).join('')}</tbody>
  </table>`;
}

function sectionText<T>(title: string, result: SectionResult<T>, renderData: (data: T) => string[]): string {
  const lines = result.ok ? renderData(result.data) : [`⚠️ This section could not load: ${result.error}`];
  return [`${title}`, ...lines.map((line) => `- ${line}`), ''].join('\n');
}

function countsText(rows: CplVendorCount[]): string {
  return rows.length === 0 ? '0' : rows.map((row) => `${row.vendor} ${row.count}`).join(', ');
}

function emptyState(message: string): string {
  return `<p style="margin:0;color:${MUTED};font-size:13px;">${escapeHtml(message)}</p>`;
}

function formatCost(value: number | 'Not tracked'): string {
  return typeof value === 'number' ? `$${value.toFixed(2)}` : value;
}

function formatDelta(value: number): string {
  return value >= 0 ? `+${value}` : String(value);
}

function titleCase(value: string): string {
  return value.charAt(0).toUpperCase() + value.slice(1);
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function escapeAttr(value: string): string {
  return escapeHtml(value);
}
